export function confirmSheet(title, text, okLabel = '确定', danger = false) {
  return new Promise(res => {
    let done = false;
    openSheet(`<h3>${esc(title)}</h3><div class="help" style="font-size:14px;color:var(--text2);margin-top:0">${text}</div>
      <div class="sheet-actions"><span class="grow"></span><button class="btn ghost" data-no>取消</button><button class="btn" data-ok style="${danger ? 'background:#D64545;color:#fff' : ''}">${esc(okLabel)}</button></div>`, sh => {
      sh.onclick = e => { if (e.target.closest('[data-ok]')) { done = true; closeSheet(); res(true); } else if (e.target.closest('[data-no]')) { closeSheet(); } };
    }, () => { if (!done) res(false); });
  });
}

